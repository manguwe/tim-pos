/// The text for the language chosen on this phone. Anything without a translation stays in English.
String tr(String english) {
  switch (AppPrefs.instance.language) {
    case 'sn':
      return shona[english] ?? english;
    case 'nd':
      return ndebele[english] ?? english;
    default:
      return english;
  }
}
